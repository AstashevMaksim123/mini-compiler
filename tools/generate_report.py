def set_run_font(run, name="Times New Roman", size=14, bold=False, italic=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def add_paragraph(doc, text, *, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=1.25):
    p = doc.add_paragraph()
    p.alignment = align
    fmt = p.paragraph_format
    fmt.first_line_indent = Cm(first_line)
    fmt.line_spacing = 1.5
    fmt.space_after = Pt(0)
    run = p.add_run(text)
    set_run_font(run, bold=bold, italic=italic)
    return p


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    fmt = p.paragraph_format
    fmt.line_spacing = 1.5
    fmt.space_after = Pt(0)
    run = p.add_run(text)
    set_run_font(run)
    return p


def add_code(doc, text):
    for line in text.strip("\n").splitlines():
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        fmt = p.paragraph_format
        fmt.left_indent = Cm(1.0)
        fmt.right_indent = Cm(0.5)
        fmt.line_spacing = 1.0
        fmt.space_after = Pt(0)
        run = p.add_run(line)
        set_run_font(run, name="Courier New", size=10)


def add_heading(doc, text, level=1):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    fmt = p.paragraph_format
    fmt.space_before = Pt(10)
    fmt.space_after = Pt(4)
    fmt.line_spacing = 1.15
    run = p.add_run(text)
    set_run_font(run, size=14 if level == 1 else 13, bold=True)
    p.style = f"Heading {level}"
    return p


def configure_page(doc):
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(14)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(0)


